import { expect, test } from '@playwright/test';
import type { components } from '../../src/types/generated';

type S = components['schemas'];
test('saved theme library supports keyboard inspection, draft edits, recovery, explicit apply, and locked books', async ({ page, request }) => {
  test.setTimeout(120_000);
  let saved: S['ThemeLibraryEntry'] | undefined;
  let attempts = 0;
  let release!: () => void;
  const extracting = new Promise<void>(resolve => { release = resolve; });
  let base: S['AppearanceResponse'];
  await page.route('**/api/v1/themes', async route => {
    const response = await route.fetch();
    const library: S['ThemeListResponse'] = await response.json();
    await route.fulfill({ json: { themes: [...(library.themes ?? []), ...(saved ? [saved] : [])] } });
  });
  await page.route('**/api/v1/themes/extract', async route => {
    attempts++;
    if (attempts === 1) { await route.fulfill({ json: { status: 'unavailable', tokens: null } }); return; }
    await extracting;
    expect(route.request().postDataJSON()).toEqual({ url: 'https://brand.example/', name: 'Example brand' });
    saved = { theme_id: 'saved-example', name: 'Example brand', source_url: 'https://brand.example/', tokens: { ...base.tokens, palette_source: 'website_extracted', color_brand_primary: '#123456' } };
    await route.fulfill({ json: { status: 'available', tokens: saved.tokens, theme_id: saved.theme_id } });
  });
  await page.goto('/');
  await page.getByRole('button', { name: 'Create book' }).click();
  await expect(page).toHaveURL(/\/sessions\//);
  const firstId = page.url().split('/').at(-1)!;
  base = await (await request.get(`http://127.0.0.1:8007/api/v1/sessions/${firstId}/appearance`)).json();
  await page.getByText('Book appearance', { exact: true }).click();
  const controls = page.getByRole('complementary', { name: 'Theme customization' });
  await controls.getByLabel('Theme name (optional)').fill('Example brand');
  await controls.getByLabel('Website URL').fill('https://brand.example/');
  await controls.getByRole('button', { name: 'Extract website theme' }).click();
  await expect(controls.getByRole('alert')).toContainText('Choose a theme or try another website');
  await controls.getByRole('button', { name: 'Extract website theme' }).click();
  await expect(controls.getByRole('status')).toHaveText('Extracting website theme...');
  await expect(controls.getByRole('button', { name: 'Apply theme' })).toBeDisabled();
  release();
  await expect(controls.getByRole('status')).toHaveText('Theme saved to library. Inspect the preview, then apply it to this book.');
  await expect(controls.getByRole('alert')).toHaveCount(0);
  await expect(controls.getByRole('radio', { name: 'Example brand' })).toHaveAttribute('aria-checked', 'true');
  expect(await (await request.get(`http://127.0.0.1:8007/api/v1/sessions/${firstId}/appearance`)).json()).toEqual(base);

  await page.goto('/');
  await page.getByRole('button', { name: 'Create book' }).click();
  await expect(page).toHaveURL(/\/sessions\//);
  const secondId = page.url().split('/').at(-1)!;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByText('Book appearance', { exact: true }).click();
  await controls.getByRole('radio', { name: 'Default', exact: true }).focus();
  await page.keyboard.press('End');
  await expect(controls.getByRole('radio', { name: 'Example brand' })).toBeFocused();
  await expect(controls.getByRole('radio', { name: 'Example brand' })).toHaveAttribute('aria-checked', 'true');
  await expect(controls.getByRole('img', { name: 'Brand primary swatch: #123456' })).toBeVisible();
  await page.keyboard.press('Tab');
  await expect(controls.getByLabel('Theme name (optional)')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(controls.getByLabel('Website URL')).toBeFocused();
  await controls.getByLabel('Footer center').fill('Example copyright');
  await controls.getByLabel('Brand primary', { exact: true }).fill('invalid');
  await expect(controls.getByLabel('Brand primary', { exact: true })).toHaveAttribute('aria-invalid', 'true');
  await expect(controls.getByRole('button', { name: 'Apply theme' })).toBeDisabled();
  await controls.getByLabel('Brand primary', { exact: true }).fill('#234567');
  await expect(controls.getByRole('alert')).toHaveCount(0);
  const preview = controls.getByTestId('page-canvas');
  expect(await preview.evaluate(element => (element as HTMLElement).style.getPropertyValue('--color-brand-primary'))).toBe('#234567');
  await expect(preview).toHaveAttribute('data-settled', 'true');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await preview.evaluate(element => {
    const bounds = element.getBoundingClientRect();
    const frame = element.closest('.page-preview')!.getBoundingClientRect();
    return bounds.width <= frame.width + 1 && bounds.height <= frame.height + 1;
  })).toBe(true);
  expect((await (await request.get(`http://127.0.0.1:8007/api/v1/sessions/${secondId}/appearance`)).json()).tokens).toEqual(base.tokens);
  await controls.getByRole('button', { name: 'Apply theme' }).click();
  await expect(controls.getByRole('status')).toHaveText('Appearance saved. Colors were checked for readable contrast.');
  const applied = await (await request.get(`http://127.0.0.1:8007/api/v1/sessions/${secondId}/appearance`)).json();
  expect(applied.tokens).toEqual({ ...saved!.tokens, palette_source: 'manual', color_brand_primary: '#234567' });
  expect(applied.chrome).toEqual({ ...base.chrome, footer_center: 'Example copyright' });
  await page.reload();
  await page.getByText('Book appearance', { exact: true }).click();
  await expect(controls.getByLabel('Brand primary', { exact: true })).toHaveValue('#234567');
  await page.getByLabel('Page text').fill('A theme applied to this book.\n\nOriginal source copy stays intact.');
  await page.getByRole('button', { name: 'Generate options' }).click();
  await expect(page.getByRole('radio', { name: /Option A/ })).toBeVisible();
  await expect(controls.getByText('Appearance is locked for this book.')).toBeVisible();
  await expect(controls.getByRole('button', { name: 'Save appearance' })).toBeDisabled();
  await expect(controls.getByLabel('Brand primary', { exact: true })).toBeDisabled();
  await expect(controls.getByRole('radio', { name: 'Example brand' })).toBeDisabled();
});
